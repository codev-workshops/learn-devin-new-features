#!/usr/bin/env node
// Cross-lab coach calibration (plan §5, W5-coach).
//
//   node labs/coach-dryrun/calibrate.mjs            check every calibration report and the table
//   node labs/coach-dryrun/calibrate.mjs --write    regenerate the table block in labs/COACH-CALIBRATION.md
//   node labs/coach-dryrun/calibrate.mjs --strict   also fail when a lab with a coach has no report yet
//   node labs/coach-dryrun/calibrate.mjs --json
//
// One deliberately generic mediocre transcript (fixtures/generic-mediocre.md, no
// lab-specific point) is graded by every per-lab coach in dry-run mode. Each coach's
// report lives in reports/<nn>-<slug>.report.json (+ .report.md, rendered by
// labs/coach-dryrun.mjs --render). This script asserts that every report is a valid,
// honest grading of that one transcript for its lab, and that all totals land within
// a MAX_SPREAD-point band.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import { parseTranscript, segmentDurations, countFillers, toSeconds, renderReportMarkdown, loadSchema, CAVEAT, ACCURACY_SHARE, TIMING_SLACK_SECONDS } from '../coach-dryrun.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const DEFAULT_LABS_DIR = path.resolve(here, '..');
export const MAX_SPREAD = 15;
export const TRANSCRIPT_REL = 'labs/coach-dryrun/fixtures/generic-mediocre.md';
export const TABLE_FILE = 'COACH-CALIBRATION.md';
export const BEGIN = '<!-- calibration:begin (generated by labs/coach-dryrun/calibrate.mjs --write) -->';
export const END = '<!-- calibration:end -->';
const LAB_DIR = /^(\d{2})-[a-z0-9][a-z0-9-]*$/;
const DIMENSIONS = ['accuracy', 'structure', 'customer_relevance', 'brevity_and_fluency', 'recovery'];

/**
 * Map a lab's coach.segments onto the generic transcript's segments:
 * framing → framing; the segments between framing and the closing `update` →
 * checkpoint-a, checkpoint-b; update → update; objection-n → objection-n.
 */
export function mapSegments(labSegments) {
  const map = {};
  const middle = [];
  for (const s of labSegments) {
    if (s.id === 'framing' || s.id === 'update' || /^objection-\d+$/.test(s.id)) map[s.id] = s.id;
    else middle.push(s.id);
  }
  const slots = ['checkpoint-a', 'checkpoint-b'];
  middle.forEach((id, i) => {
    if (slots[i]) map[id] = slots[i];
  });
  return map;
}

function expectedVerdict(delta, tolerance) {
  if (Math.abs(delta) <= tolerance) return 'on';
  return delta < 0 ? 'under' : 'over';
}

async function exists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

const readJson = async (p) => JSON.parse(await fs.readFile(p, 'utf8'));

function median(xs) {
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

export async function runCalibration({ labsDir = DEFAULT_LABS_DIR, strict = false } = {}) {
  const failures = [];
  const fail = (m) => failures.push(m);
  const calDir = path.join(labsDir, 'coach-dryrun');
  const transcriptText = await fs.readFile(path.join(calDir, 'fixtures', 'generic-mediocre.md'), 'utf8');
  const transcript = parseTranscript(transcriptText);
  const durations = segmentDurations(transcript);
  const plantedFillers = transcript.data.planted_fillers;
  const countedFillers = countFillers(transcript.learnerText).total;
  if (countedFillers !== plantedFillers) fail(`transcript contains ${countedFillers} filler(s) but plants ${plantedFillers}`);
  const plantedPauses = (transcript.data.planted_long_pauses ?? []).map(String);

  const ajv = new Ajv({ allErrors: true, strict: true });
  ajv.addFormat('date-time', (s) => !Number.isNaN(Date.parse(s)));
  const validate = ajv.compile(await loadSchema(labsDir));

  const rows = [];
  const pending = [];
  const dirs = (await fs.readdir(labsDir, { withFileTypes: true })).filter((e) => e.isDirectory() && LAB_DIR.test(e.name)).map((e) => e.name).sort();
  for (const dir of dirs) {
    const labJsonPath = path.join(labsDir, dir, 'lab.json');
    if (!(await exists(labJsonPath))) continue;
    const lab = await readJson(labJsonPath);
    const segments = lab.coach?.segments ?? [];
    if (!lab.coach?.skill || !segments.length) continue;
    const reportPath = path.join(calDir, 'reports', `${dir}.report.json`);
    if (!(await exists(reportPath))) {
      pending.push(dir);
      if (strict) fail(`${dir}: no calibration report (reports/${dir}.report.json)`);
      continue;
    }
    const r = await readJson(reportPath);
    const f = (m) => fail(`${dir}: ${m}`);
    if (!validate(r)) {
      for (const e of validate.errors) f(`schema ${e.instancePath || '/'} ${e.message}`);
      continue;
    }
    if (r.lab.number !== lab.number) f(`lab.number ${r.lab.number} != ${lab.number}`);
    if (r.lab.coach !== lab.coach.skill) f(`lab.coach ${r.lab.coach} != ${lab.coach.skill}`);
    if (r.mode !== 'dry-run') f('mode must be dry-run');
    if (r.run.transcript !== TRANSCRIPT_REL) f(`run.transcript must be ${TRANSCRIPT_REL}`);

    const map = mapSegments(segments);
    const ids = segments.map((s) => s.id);
    const seen = r.timing.map((t) => t.segment);
    for (const id of ids) if (!seen.includes(id)) f(`timing is missing segment "${id}"`);
    for (const id of seen) if (!ids.includes(id)) f(`timing has unknown segment "${id}"`);
    if (new Set(seen).size !== seen.length) f('duplicate timing segments');
    let offTarget = 0;
    for (const t of r.timing) {
      const seg = segments.find((s) => s.id === t.segment);
      if (!seg) continue;
      if (t.target_seconds !== seg.target_seconds) f(`${t.segment} target_seconds ${t.target_seconds} != lab.json ${seg.target_seconds}`);
      const generic = map[t.segment];
      const want = generic ? durations[generic] : undefined;
      if (want == null) f(`${t.segment} has no generic transcript segment to map onto`);
      else if (Math.abs(want - t.actual_seconds) > TIMING_SLACK_SECONDS) f(`${t.segment} actual_seconds ${t.actual_seconds} disagrees with ${generic} markers (${want} s)`);
      if (t.delta_seconds !== t.actual_seconds - t.target_seconds) f(`${t.segment} delta_seconds must be actual - target`);
      const v = expectedVerdict(t.delta_seconds, r.run.timing_tolerance_seconds);
      if (t.verdict !== v) f(`${t.segment} verdict "${t.verdict}" should be "${v}"`);
      if (t.verdict !== 'on') offTarget++;
    }

    if (r.stems.length !== 3) f('exactly three stems required');
    if (r.clarity.caveat !== CAVEAT) f(`clarity.caveat must be "${CAVEAT}"`);
    const s = r.scores;
    const sum = DIMENSIONS.reduce((a, k) => a + s[k].score, 0);
    if (sum !== s.total) f(`scores.total ${s.total} != sum of parts ${sum}`);
    const weightSum = r.must_mention.reduce((a, m) => a + m.weight, 0);
    if (weightSum !== ACCURACY_SHARE) f(`must-mention weights sum to ${weightSum}, expected ${ACCURACY_SHARE}`);
    for (const m of r.must_mention) {
      if (m.mentioned) f(`must_mention ${m.id} marked mentioned, but the generic transcript names no lab-specific point`);
      if (!ids.includes(m.belonged_in)) f(`must_mention ${m.id} belonged_in "${m.belonged_in}" is not a segment`);
    }
    const ownMediocre = path.join(labsDir, dir, 'coaching', 'dryrun', 'mediocre.report.json');
    let own = {};
    if (await exists(ownMediocre)) {
      const mr = await readJson(ownMediocre);
      const want = mr.must_mention.map((m) => `${m.id}:${m.weight}`).join(',');
      const got = r.must_mention.map((m) => `${m.id}:${m.weight}`).join(',');
      if (want !== got) f(`must_mention ids/weights [${got}] differ from the lab's own dry run [${want}]`);
      own.mediocre = mr.scores.total;
      const off = path.join(labsDir, dir, 'coaching', 'dryrun', 'off-track.report.json');
      if (await exists(off)) own.offTrack = (await readJson(off)).scores.total;
    }
    if (Math.abs(r.fillers_and_pauses.filler_count - plantedFillers) > 1) f(`filler_count ${r.fillers_and_pauses.filler_count} not within ±1 of planted ${plantedFillers}`);
    for (const at of plantedPauses) {
      if (!r.fillers_and_pauses.long_pauses.some((p) => Math.abs(toSeconds(p.at) - toSeconds(at)) <= TIMING_SLACK_SECONDS)) f(`planted long pause at ${at} not reported`);
    }
    const mdPath = reportPath.replace(/\.json$/, '.md');
    if (!(await exists(mdPath))) f('report .md missing');
    else if ((await fs.readFile(mdPath, 'utf8')) !== renderReportMarkdown(r)) f(`report .md is stale — regenerate with node labs/coach-dryrun.mjs --render ${path.relative(process.cwd(), reportPath)}`);

    rows.push({
      dir,
      number: lab.number,
      coach: lab.coach.skill,
      scores: Object.fromEntries(DIMENSIONS.map((k) => [k, s[k].score])),
      total: s.total,
      offTarget,
      segments: segments.length,
      objections: segments.filter((x) => x.kind === 'objection').length,
      ownMediocre: own.mediocre ?? null,
      ownOffTrack: own.offTrack ?? null,
    });
  }

  const totals = rows.map((r) => r.total);
  const band = totals.length ? { min: Math.min(...totals), max: Math.max(...totals), median: median(totals) } : null;
  if (band) {
    band.spread = band.max - band.min;
    if (band.spread > MAX_SPREAD) {
      const lo = rows.filter((r) => r.total === band.min).map((r) => r.dir);
      const hi = rows.filter((r) => r.total === band.max).map((r) => r.dir);
      fail(`spread ${band.spread} > ${MAX_SPREAD}: lowest ${band.min} (${lo.join(', ')}), highest ${band.max} (${hi.join(', ')}); adjust the outlying lab's own skill anchors or weights, never the base`);
    }
  } else fail('no calibration reports found');

  return { ok: failures.length === 0, failures, rows, band, pending };
}

export function renderCalibrationTable({ rows, band, pending }) {
  const L = [];
  L.push('| Lab | Coach | Accuracy /30 | Structure /25 | Relevance /20 | Brevity /15 | Recovery /10 | **Total** | vs median | Segments off target | Own mediocre / off-track |');
  L.push('| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |');
  for (const r of rows) {
    const d = r.total - band.median;
    L.push(
      `| ${r.dir} | \`${r.coach}\` | ${r.scores.accuracy} | ${r.scores.structure} | ${r.scores.customer_relevance} | ${r.scores.brevity_and_fluency} | ${r.scores.recovery} | **${r.total}** | ${d > 0 ? '+' : ''}${d} | ${r.offTarget} of ${r.segments} | ${r.ownMediocre ?? '–'} / ${r.ownOffTrack ?? '–'} |`,
    );
  }
  L.push('');
  L.push(`Band: ${rows.length} coaches, totals ${band.min}–${band.max}, median ${band.median}, **spread ${band.spread}** (limit ${MAX_SPREAD}) — ${band.spread <= MAX_SPREAD ? 'within band' : 'OUT OF BAND'}.`);
  L.push('');
  L.push(`Pending (lab has a coach but no calibration report yet): ${pending.length ? pending.join(', ') : 'none'}.`);
  return L.join('\n');
}

export function spliceTable(doc, table) {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${TABLE_FILE} needs the ${BEGIN} … ${END} markers`);
  return `${doc.slice(0, a + BEGIN.length)}\n${table}\n${doc.slice(b)}`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const argv = process.argv.slice(2);
  const strict = argv.includes('--strict');
  const write = argv.includes('--write');
  const asJson = argv.includes('--json');
  const labsDir = DEFAULT_LABS_DIR;
  const result = await runCalibration({ labsDir, strict });
  const docPath = path.join(labsDir, TABLE_FILE);
  if (result.band) {
    const table = renderCalibrationTable(result);
    const doc = await fs.readFile(docPath, 'utf8');
    const next = spliceTable(doc, table);
    if (write) await fs.writeFile(docPath, next);
    else if (next !== doc) result.failures.push(`${TABLE_FILE} table is stale — run node labs/coach-dryrun/calibrate.mjs --write`);
    result.ok = result.failures.length === 0;
    if (!asJson) console.log(table);
  }
  if (asJson) console.log(JSON.stringify(result, null, 2));
  else if (result.ok) console.log('\ncoach calibration OK');
  else {
    console.log(`\ncoach calibration FAILED (${result.failures.length}):`);
    for (const f of result.failures) console.log(` - ${f}`);
  }
  process.exit(result.ok ? 0 : 1);
}
